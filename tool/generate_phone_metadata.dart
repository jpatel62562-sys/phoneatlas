String countryFlagFromIso(String isoCode) {
  if (isoCode.length != 2) return '';
  final upper = isoCode.toUpperCase();
  final first = upper.codeUnitAt(0) - 0x41 + 0x1F1E6;
  final second = upper.codeUnitAt(1) - 0x41 + 0x1F1E6;
  return String.fromCharCode(first) + String.fromCharCode(second);
}

void main() {
  print('Generating PhoneAtlas metadata...');

  final buffer = StringBuffer();
  buffer.writeln('// GENERATED CODE - DO NOT MODIFY BY HAND');
  buffer.writeln('// Generated by tool/generate_phone_metadata.dart');
  buffer.writeln(
    '// Source: Google libphonenumber metadata (via phone_numbers_parser)',
  );
  buffer.writeln('// Date: ${DateTime.now().toUtc().toIso8601String()}');
  buffer.writeln();
  buffer.writeln("import '../models/country.dart';");
  buffer.writeln();
  buffer.writeln(
    '/// Complete collection of standardized countries for PhoneAtlas.',
  );
  buffer.writeln('class CountriesData {');
  buffer.writeln('  const CountriesData._();');
  buffer.writeln();
  buffer.writeln('  /// All 245+ supported countries and territories.');
  buffer.writeln('  static const List<Country> all = [');

  final sortedEntries = <Map<String, dynamic>>[];

  for (final iso in IsoCode.values) {
    final isoStr = iso.name;
    final name = _canonicalNames[isoStr] ?? isoStr;
    final meta = MetadataFinder.findMetadataForIsoCode(iso);
    final lengths = MetadataFinder.findMetadataLengthForIsoCode(iso);

    final allLengths = <int>{
      ...lengths.general,
      ...lengths.mobile,
      ...lengths.fixedLine,
    };
    final minLen = allLengths.isEmpty
        ? 4
        : allLengths.reduce((a, b) => a < b ? a : b);
    final maxLen = allLengths.isEmpty
        ? 15
        : allLengths.reduce((a, b) => a > b ? a : b);
    final dialCode = '+${meta.countryCode}';
    final flag = countryFlagFromIso(isoStr);

    sortedEntries.add({
      'isoCode': isoStr,
      'name': name,
      'dialCode': dialCode,
      'flag': flag,
      'minLength': minLen,
      'maxLength': maxLen,
    });
  }

  // Sort by country name alphabetically
  sortedEntries.sort(
    (a, b) => (a['name'] as String).compareTo(b['name'] as String),
  );

  for (final entry in sortedEntries) {
    buffer.writeln('    Country(');
    buffer.writeln("      name: '${entry['name']}',");
    buffer.writeln("      isoCode: '${entry['isoCode']}',");
    buffer.writeln("      dialCode: '${entry['dialCode']}',");
    buffer.writeln("      flag: '${entry['flag']}',");
    buffer.writeln('      minLength: ${entry['minLength']},');
    buffer.writeln('      maxLength: ${entry['maxLength']},');
    buffer.writeln('    ),');
  }

  buffer.writeln('  ];');
  buffer.writeln('}');

  final outputFile = File('lib/src/data/countries.dart');
  outputFile.parent.createSync(recursive: true);
  outputFile.writeAsStringSync(buffer.toString());

  print(
    'Successfully generated ${sortedEntries.length} countries to ${outputFile.path}!',
  );
}
